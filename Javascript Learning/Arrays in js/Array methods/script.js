const arr = [28, 33, 46, 56, 67, 78];
// adds an value of an array
arr.push(100);
// take an last value
arr.pop();
// add the value at the beginning
arr.unshift(true);
// remove the value at the beginning
arr.shift();
// reverse an array
arr.reverse();

// validation methods
x = arr.includes(3536);

// conversion methods
x = arr.toString();
console.log(x, typeof x);
